 #Objetivo: Leia um numero inteiro e informe se ele e par ou impar.

n = int(input("Digite um numero inteiro: "))#ta falando para digitar um numero inteiro

if n % 2 == 0: #ta falando que se o resultado da conta por 2 der zero vai ser par se não der zero vai ser impar 
    print("O numero é par.") #resultado final
else:
    print("O numero é impar.") #resultado final