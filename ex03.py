# Objetivo: Leia três notas (podem ter casas decimais) e mostre a média aritmética
nota1 = float(input("Digite a primeira nota: "))# falando para digitar a primeira nota

nota2 = float(input("Digite a segunda nota: "))# falando para digitar a segunda nota

nota3 = float(input("Digite a terceira nota: "))# falando para digitar a terceira nota

media = (nota1 + nota2 + nota3) / 3 # calcular a média do estudante

print("A média é: " + str(media))# resultado final