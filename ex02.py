#Objetivo: Leia dois números inteiros e mostre a soma, a subtração (primeiro menos o segundo) e a multiplicação entre
#eles.
a = int(input("Digite a primeira nota: "))# falando para digitar o primeiro número

b = int(input("Digite a segunda nota: "))# falando para digitar o segundo número

soma = a + b#fazer a soma
subtracao = a - b#fazer a subtração
multiplicacao = a * b#fazer a multiplicação
# resultado final
print("A Nota é: " + str(soma)  )
print("A Subtração é: " + str(subtracao)  )
print("A Multiplicação é: " + str(multiplicacao)  )
