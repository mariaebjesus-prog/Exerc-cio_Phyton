# Objetivo: Leia a idade de uma pessoa e informe se ela é maior de idade (18 anos ou mais) ou menor de idade
idade = int(input("Digite asua  idade: "))# tafalando para digitar a sua idade

if idade >= 18:
    print("Você é maior de idade.")# ta falanod se vc tem 18 anos ou mais vc é maior de idade
else:
    print("Você é menor de idade.")# ta falando se vc tem menos de 18 anos vc é menor de idade