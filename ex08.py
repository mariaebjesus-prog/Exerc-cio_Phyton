#Objetivo:Leia um número inteiro e informe se ele é positivo ou negativo. Neste exercício, considere o zero comopositivo.
numero = int(input("Digite um número inteiro: ")) # ta falando para digitar um número

if numero >= 0:
    print("Seu número é positivo.")# ta falando que se for maior ou igual a 0 é positivo
else:
    print("Seu número é negativo.")# ta falado que sefor menor que 0 é negativo