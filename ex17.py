#  Objetivo: Positivo, negativo ou zero
numero = float(input("Digite um número: "))#ta falando para digitar um numero
if numero > 0:
    print("O número é positivo.")#ta falando que se o numero for maior que 0 é positivo
elif numero < 0:
    print("O número é negativo.")#ta falando que se o numero for menor que 0 é negativo
else:
    print("O número é zero.") #ta falando que se o numero for igual a 0 é zero 
