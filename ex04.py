# Objetivo: Leia uma temperatura em graus Celsius e mostre o valor em Fahrenheit. Fórmula: F = C × 1.8 + 32
C = float(input("Digite a temperatura : "))# falando para digitar a temperatura em Celsius

F = C * 1.8 + 32# ta mostrando como faz a conta para chegar ao resultado

print("A temperatura em Fahrenheit é: " + str(F) + "°F")# resultado final